"""Index existing raw artifacts by category without moving or loading them."""

import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
import json
import os
from pathlib import Path
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]


def category(relative):
    if len(relative.parts) == 1:
        return 'dashcam' if relative.name.startswith('dashcam_') else 'legacy'
    if relative.parts[0] == 'rl_training' and len(relative.parts) > 2:
        cache = relative.parts[1].removeprefix('contacts_')
        if len(cache) == 16 and all(c in '0123456789abcdef' for c in cache):
            return 'rl_training/build_cache'
    return relative.parts[0]


def collect(log_root, output):
    groups = defaultdict(list)
    for directory, subdirs, files in os.walk(log_root, followlinks=False):
        subdirs[:] = sorted(name for name in subdirs
                            if not name.startswith('.')
                            and not (Path(directory) / name).resolve().is_relative_to(output))
        for name in sorted(files):
            path = Path(directory) / name
            if path.is_symlink() or path.resolve().is_relative_to(output):
                continue
            try:
                stat = path.stat()
            except FileNotFoundError:
                continue
            relative = path.relative_to(log_root)
            groups[category(relative)].append({
                'path': relative.as_posix(), 'bytes': stat.st_size,
                'modified_utc': datetime.fromtimestamp(stat.st_mtime, timezone.utc).isoformat(),
            })
    return groups


def write_catalog(log_root, output, groups):
    output.mkdir(parents=True, exist_ok=True)
    data = {
        'generated_utc': datetime.now(timezone.utc).isoformat(),
        'log_root': os.path.relpath(log_root, output),
        'file_count': sum(len(files) for files in groups.values()),
        'categories': {},
    }
    lines = ['# Local Raw Log Catalog', '',
             'Generated by `make catalog-logs`. Source artifacts stay at their original paths.',
             'Paths in [index.json](index.json) are relative to `log_root` in that file.', '',
             '| Category | Files | MiB |', '| --- | ---: | ---: |']
    for name, files in sorted(groups.items()):
        files.sort(key=lambda record: record['path'])
        total = sum(record['bytes'] for record in files)
        data['categories'][name] = {
            'file_count': len(files), 'bytes': total,
            'extensions': dict(sorted(Counter(Path(record['path']).suffix or '(none)'
                                              for record in files).items())),
            'files': files,
        }
        lines.append(f'| {name} | {len(files)} | {total / 1024**2:.2f} |')
    for name, files in sorted(groups.items()):
        lines.extend(['', f'## {name}: Recently Modified', ''])
        for record in sorted(files, key=lambda row: row['modified_utc'], reverse=True)[:10]:
            target = quote(Path(os.path.relpath(log_root / record['path'], output)).as_posix())
            lines.append(f"- [{record['path']}]({target}) ({record['modified_utc']})")
    (output / 'index.json').write_text(json.dumps(data, ensure_ascii=True, indent=2) + '\n')
    (output / 'index.md').write_text('\n'.join(lines) + '\n')
    return data['file_count']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT / 'logs')
    parser.add_argument('--out', type=Path, help='Default: <root>/catalog')
    args = parser.parse_args()
    log_root = args.root.resolve()
    output = (args.out or log_root / 'catalog').resolve()
    if not log_root.is_dir():
        parser.error(f'Log directory does not exist: {log_root}')
    if log_root == output or log_root.is_relative_to(output):
        parser.error('Output must not contain the source log directory')
    groups = collect(log_root, output)
    count = write_catalog(log_root, output, groups)
    print(f'Indexed {count} artifacts in {len(groups)} categories: {output / "index.md"}')


if __name__ == '__main__':
    main()
