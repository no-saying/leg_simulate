#!/usr/bin/env python3
"""Generate the rolling terrain elevation data for the simulation.

Replaces the old box-shaped ramp/bumps with smooth gaussian humps and pits
so the balance robot gets a natural, continuous off-road section instead of
staircase steps.

Writes model/terrain_hfield_include.xml containing an <hfield> asset whose
elevation attribute carries the data directly in XML (no binary file needed).
The robot spawns at the origin on flat ground; the rough section starts at
x ~ 3 m so the spawn pose never intersects the heightfield solid.
"""

import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "model", "terrain_hfield_include.xml")

# Grid samples and world-space extent of the terrain.
NX, NY = 100, 28           # ncol, nrow
SX, SY = 30.0, 14.0        # footprint x ∈ [-15,15], y ∈ [-7,7]

# Hfield spans x ∈ [-15,15] in its local frame. We want the robot (spawns at
# world x=0) to start on flat ground and the rough section ahead in +x, so the
# geom is offset so that the terrain's useful part covers world x ∈ [0,16].
GEOM_X = 3.5

# Base terrain surface height: world z where flat ground is. The flat plane
# geom stays at z=-0.26; we keep the hfield surface at the same level.
GROUND_Z = -0.26

# Terrain features (x along the driving direction, world coordinates;
#  spawn at x=0 stays flat, rough section starts around x=3):
#   (center_x, center_y, sigma_x, sigma_y, peak_world_z, is_pit)
FEATURES = [
    # Rolling humps and pits along the path.
    (4.0, 0.0, 1.4, 2.2, 0.32, False),
    (5.6, 0.0, 1.0, 1.4, -0.22, True),
    (7.2, 0.0, 1.2, 2.4, 0.36, False),
    (8.8, 0.0, 0.9, 1.3, -0.20, True),
    (10.2, 0.0, 1.2, 2.0, 0.30, False),
    (11.8, 0.0, 1.0, 1.5, -0.18, True),
    (13.2, 0.0, 1.2, 2.2, 0.34, False),
    (14.8, 0.0, 0.9, 1.4, -0.20, True),
    (16.2, 0.0, 1.1, 1.8, 0.28, False),
    # Off-path bumps so the sides are interesting too.
    (8.0, 3.4, 1.3, 1.2, 0.26, False),
    (12.0, -3.2, 1.4, 1.2, 0.28, False),
]


def main() -> None:
    heights = [[0.0] * NX for _ in range(NY)]
    for iy in range(NY):
        wy = -SY / 2.0 + (iy + 0.5) * (SY / NY)
        for ix in range(NX):
            wx = -SX / 2.0 + (ix + 0.5) * (SX / NX)
            wx_world = wx + GEOM_X
            z = 0.0
            for cx, cy, sx, sy, peak, pit in FEATURES:
                dx = (wx_world - cx) / sx
                dy = (wy - cy) / sy
                g = math.exp(-0.5 * (dx * dx + dy * dy))
                z += -g * peak if pit else g * peak
            heights[iy][ix] = GROUND_Z + z

    h_min = min(min(row) for row in heights)
    h_max = max(max(row) for row in heights)
    span = h_max - h_min
    if span < 1e-9:
        span = 1e-9

    # MuJoCo normalizes elevation to [0,1]; size[2]=elevation_z scales it and
    # the minimum lands at geom z + base_z. To make flat ground at GROUND_Z:
    #   GROUND_Z = pos.z + base_z + (GROUND_Z - h_min)/span * elevation_z
    # Choose base_z = 0.03 and elevation_z = span, then solve for pos.z.
    base_z = 0.03
    elevation_z = span
    pos_z = GROUND_Z - base_z - ((GROUND_Z - h_min) / span) * elevation_z

    # XML `elevation` rows are bottom-to-top in the model, so we emit the
    # grid reversed (visual check happens in the GUI; symmetric-ish features
    # mean a flip is not critical).
    rows = []
    for row in reversed(heights):
        rows.append(" ".join("%.3f" % v for v in row))
    elevation = "\n                    ".join(rows)

    include = (
        '<mujoco model="terrain_include">\n'
        '    <hfield name="terrain_h" nrow="%d" ncol="%d"\n'
        '            size="%.3f %.3f %.3f %.3f"\n'
        '            elevation="\n                    %s"/>\n'
        '</mujoco>\n'
    ) % (NY, NX, SX / 2.0, SY / 2.0, elevation_z, base_z, elevation)

    with open(OUT, "w") as f:
        f.write("<!-- generated by scripts/gen_terrain_hfield.py -->\n")
        f.write(include + "\n")

    # Report feature heights relative to ground for a quick sanity check.
    for cx, cy, sx, sy, peak, pit in FEATURES:
        print("feature %+.2f,%+.2f peak=%+.2f m" % (cx, cy, peak))
    print("grid %dx%d over %.1fx%.1f m -> hfield %d,%d" % (NX, NY, SX, SY, NX, NY))
    print("data z range %.3f .. %.3f" % (h_min, h_max))
    print("geom pos: x=%.2f z=%.4f  base_z=%.3f elevation_z=%.3f" % (GEOM_X, pos_z, base_z, elevation_z))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
