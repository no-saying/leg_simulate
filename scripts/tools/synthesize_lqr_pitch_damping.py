"""Synthesize pitch wheel feedback from a PID fit with uncertain rate damping."""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from scipy.linalg import solve_discrete_are

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    args = parser.parse_args()
    raw = args.report.read_bytes()
    report = json.loads(raw)
    if not report.get("pid_only") or not report.get("accepted"):
        raise ValueError("Requires an accepted model collected under pure PID")
    dt = report["dt_model"]
    gains, checks = [], []
    for segment in report["segs"]:
        identified_a = np.asarray(segment["pitch3_A"])
        b = np.asarray(segment["pitch3_B"])
        design_a = identified_a.copy()
        # A rigid body's angular rate has no guaranteed free damping. The
        # reduced PID fit aliases leg damping into this coefficient; relying
        # on it produced negative rate feedback and a real pitch limit cycle.
        design_a[1, 1] = 1.0
        design_a[0] = np.eye(3)[0] + .5 * dt * (np.eye(3)[1] + design_a[1])
        q, r = np.diag([900., .10, 2.]), np.array([[.60]])
        p = solve_discrete_are(design_a, b, q, r)
        k = np.linalg.solve(r + b.T @ p @ b, b.T @ p @ design_a)
        radii = [float(max(abs(np.linalg.eigvals(a - b @ k))))
                 for a in (identified_a, design_a)]
        if k[0, 0] <= 0 or k[0, 1] <= 0 or max(radii) >= 1:
            raise ValueError(f"Unstable pitch design at {segment['point_id']}: {radii}")
        gains.append(k[0])
        checks.append(dict(point_id=segment["point_id"], K=k[0].tolist(),
                           identified_radius=radii[0], conservative_radius=radii[1]))
    lines = ["/* Generated by synthesize_lqr_pitch_damping.py from pure PID data.",
             f" * Source SHA256: {hashlib.sha256(raw).hexdigest()}",
             " * Rate damping is uncertain; synthesis assumes no free damping. */",
             "#ifndef LQR_PITCH_DAMPED_MODELS_H", "#define LQR_PITCH_DAMPED_MODELS_H", "",
             f"#define LQR_PITCH_DAMPED_N {len(gains)}",
             "#if LQR_PITCH_DAMPED_N != LQR_N_SEG",
             '#error "Pitch damping gains must match the PID model segments"',
             "#endif", "",
             "static const float lqr_pitch_damped_K[LQR_PITCH_DAMPED_N][3] = {"]
    lines += ["    { " + ", ".join(f"{value:.8e}f" for value in k) + " }," for k in gains]
    lines += ["};", "", "#endif", ""]
    header = ROOT / "control/controllers/lqr/lqr_pitch_damped_models.h"
    header.write_text("\n".join(lines))
    verification = ROOT / "logs/manual_verification"
    verification.mkdir(parents=True, exist_ok=True)
    (verification / "pitch_damping_design.json").write_text(
        json.dumps(dict(source=str(args.report), dt=dt, segments=checks), indent=2))
    print(f"Generated {header.name}: {len(gains)} PID model segments; "
          f"rate gain {min(k[1] for k in gains):.3f}..{max(k[1] for k in gains):.3f}")


if __name__ == "__main__":
    main()
